from __future__ import annotations


Part = str | tuple[str, str]
Spec = tuple[str, tuple[Part, ...]]


def build_paraphrase_v3_specs() -> list[Spec]:
    """Training-only paraphrases kept independent from every blind corpus."""
    specs: list[Spec] = []

    def add(intent: str, *parts: Part) -> None:
        specs.append((intent, parts))

    tasks = [
        "записать питомца на вакцинацию", "получить справку из архива", "заправить картридж принтера",
        "согласовать макет визитки", "вернуть роутер провайдеру", "заказать чистку кондиционера",
        "перенести фотографии на диск", "проверить баланс школьной карты", "забрать обувь из ремонта",
        "сверить серийный номер насоса", "отправить показания теплосчётчика", "пополнить запас корма",
        "купить батарейки для датчика", "подписать акт у мастера", "загрузить документы в кабинет",
        "уточнить график доставки", "проверить гарантию пылесоса", "вернуть пропуск на проходную",
        "заказать фильтры для увлажнителя", "обновить контакт аварийной службы",
    ]
    reminder_patterns: list[tuple[Part, ...]] = [
        ("Просигналь мне вовремя:",),
        ("Возьми под контроль необходимость",),
        ("Зафиксируй как предстоящее дело",),
        ("Поставь в очередь моих дел",),
        ("Не упусти момент, когда потребуется",),
        ("Вернись со мной к задаче",),
        ("В будущем потребуется",),
        ("Включи в перечень будущих действий",),
    ]
    for prefix in reminder_patterns:
        for task in tasks:
            add("create_reminder", *prefix, (task, "TEXT"))
    for task in tasks:
        add("create_reminder", ("Во вторник", "DATE"), "потребуется", (task, "TEXT"))
        add("create_reminder", "Держи в уме", (task, "TEXT"), ("вечером", "TIME"))

    periods = ["сегодня", "завтра", "на выходных", "на следующей неделе", "до конца месяца"]
    list_patterns = [
        "Сделай обзор моих будущих задач", "Какая у меня ожидается загрузка", "Перечисли ближайшие обязательства",
        "Что находится в очереди дел", "Покажи сводку предстоящих действий", "Чем предстоит заниматься",
        "Какие пункты ещё ожидают исполнения", "Выведи календарную сводку", "Что назначено к выполнению",
        "Проверь перечень будущих задач", "Как выглядит моя занятость", "Сколько дел ожидает выполнения",
    ]
    for prefix in list_patterns:
        for period in periods:
            add("list_reminders", prefix, (period, "DATE"))

    delete_patterns = [
        "Отзови задачу", "Убери из очереди дел", "Сними с исполнения", "Отметь как отменённую задачу",
        "Сотри пункт расписания", "Исключи из перечня дел", "Отмени выполнение задачи",
        "Больше не учитывай задачу", "Закрой пункт", "Откажись от выполнения",
    ]
    for prefix in delete_patterns:
        for task in tasks:
            add("delete_reminder", prefix, (task, "TARGET"))
    for phrase in [
        "Отзови последний пункт", "Исключи самую свежую задачу", "Последнее дело больше не учитывать",
        "Закрой последний пункт расписания", "Сними с исполнения последнюю задачу",
    ]:
        add("delete_reminder", phrase)

    note_bodies = [
        "код ячейки хранения 5142", "номер заявки сервиса SR-9081", "размер крепления 62 миллиметра",
        "контакт диспетчера 89047773311", "маркировка кабеля NYM 3x2.5", "адрес пункта ремонта Советская 44",
        "рецепт раствора одна ложка на литр", "идея фотографировать показания приборов",
        "серия гарантийного талона GT-44109", "название детали муфта двадцать пять",
        "логин учебного портала student-407", "номер парковочного абонемента 51903",
        "модель зарядного устройства EP-TA800", "результат замера ширина 117 высота 204",
        "мысль проверять резервную копию ежемесячно", "телефон дежурного электрика 89041239876",
    ]
    note_patterns = [
        "Внеси в личные записи:", "Сохрани как справочную информацию:", "Создай текстовую карточку:",
        "Запиши без пересказа:", "Добавь в мою память:", "Оформи отдельной записью:",
        "Зафиксируй для последующего чтения:", "Пусть сохранится следующий текст:",
    ]
    for prefix in note_patterns:
        for body in note_bodies:
            add("create_note", prefix, (body, "TEXT"))

    folders = [
        "Сервис бытовой техники", "Документы питомца", "Учёт коммунальных приборов",
        "Материалы для мастерской", "Семейный архив фото", "Инструкции оборудования",
        "Контакты экстренных служб", "Заказы для ремонта", "Учебные сертификаты",
        "Договоры с провайдерами", "Расходники для дома", "История обращений в сервис",
    ]
    for prefix in [
        "Открой новую папку", "Организуй категорию", "Создай коллекцию", "Заведи секцию",
        "Сделай отдельный каталог", "Добавь хранилище записей", "Сформируй новый раздел",
    ]:
        for folder in folders:
            add("create_folder", prefix, (folder, "FOLDER"))
    for prefix in [
        "Упраздни папку", "Закрой категорию", "Сотри коллекцию", "Удали секцию",
        "Ликвидируй каталог", "Расформируй хранилище записей", "Исключи раздел",
    ]:
        for folder in folders:
            add("delete_folder", prefix, (folder, "FOLDER"))

    unknown_patterns = [
        "Объясни, как лучше", "Я уже успел", "Стоит ли вообще", "Кто может помочь",
        "Почему важно", "Я пока не собираюсь", "Найди инструкцию, как", "Оцени сложность задачи",
        "Мне рассказали, как", "Что будет, если не", "Я сомневаюсь, нужно ли", "Научи меня",
    ]
    for prefix in unknown_patterns:
        for task in tasks:
            add("unknown", prefix, task)
    for phrase in [
        "Отзови", "Сотри это", "Закрой окно приложения", "Исключи все данные", "Покажи карточки заметок",
        "Объедини две категории", "Перемести запись в другой раздел", "Очисти историю ввода",
        "Отправь документы по почте", "Открой список контактов", "Проверь обновления приложения",
    ]:
        add("unknown", phrase)

    return specs
