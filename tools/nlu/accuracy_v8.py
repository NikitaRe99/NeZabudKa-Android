"""General query/carrier coverage, without importing the frozen manual trial."""
from dataset import marked


def build_accuracy_examples():
    values = set()
    periods = ["сегодня", "послезавтра", "через неделю", "в понедельник",
               "на следующую среду", "в следующий четверг", "на следующую неделю",
               "на следующий год", "на выходные", "на этот месяц"]
    queries = ["дай посмотреть мои дела", "дай посмотреть напоминания",
               "можно посмотреть расписание", "отобрази напоминания",
               "выведи дела", "покажи расписание", "какие дела запланированы",
               "мне интересен список задач", "хочу увидеть мои планы",
               "покажи что у меня запланировано", "есть ли напоминания"]
    for prefix in queries:
        for period in periods:
            for before, after in [("", ""), ("пожалуйста ", ""), ("", ", пожалуйста"), ("", "?")]:
                values.add(marked("list_reminders", before + prefix, (period, "DATE"), after))
    bodies = ["синий футляр лежит возле очков", "стрелка часов остановилась",
              "паспорт находится в зелёном ящике", "крепление антенны нужно проверить",
              "мысль о поездке появилась вчера", "возле часов стоит небольшая коробка"]
    for body in bodies:
        for prefix in ["зафиксируй такую мысль", "запиши мысль", "хочу сохранить запись о том что",
                       "оставь заметку о том, что", "сохрани такую запись"]:
            values.add(marked("create_note", prefix, (body, "TEXT")))
        for folder in ["Личные материалы", "Домашние проекты", "Справочник"]:
            for action in ["оставь", "запиши", "сохрани"]:
                for connector in ["о том что", "о том, что"]:
                    values.add(marked("create_note", action + " запись в папке", (folder, "FOLDER"), connector, (body, "TEXT")))
    for text in ["покажи расписание автобусов", "дай посмотреть прогноз погоды на завтра",
                 "отобрази фотографии", "расскажи про мои планы", "не показывай напоминания",
                 "отмени просмотр расписания", "измени расписание на послезавтра",
                 "перенеси все дела на понедельник", "какие фильмы посмотреть на выходных",
                 "покажи часы", "отобрази заметки", "покажи список папок"]:
        values.add(marked("unknown", text))
    return sorted(values, key=lambda e: (e.intent, e.text, e.spans))
